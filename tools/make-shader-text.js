// make-shader-text.js: THE RENDERER'S SHADERS, BUILT INTO THE EDITOR (the owner's "baked in", 2026-11-19, Bishop's order). Every .vsh, .psh and .fxh of avpx/shaders (the
// pinned AvPx's own) becomes src/host/shader_text_data.cpp: each file's text as a byte array, its name as the renderer asks for it. A CRLF is read as LF, so every checkout makes
// the same file (the compile's code doesn't depend on it). NEVER EDIT shader_text_data.cpp BY HAND: run this from the tree's root after the avpx pin moves.
//   node tools/make-shader-text.js            writes src/host/shader_text_data.cpp
//   node tools/make-shader-text.js --check    exit 0 when the file is what avpx/shaders makes, 1 (and why) when not
// host_shader_text_test checks the same against the files. Written 2026-11-19 by Melanikus (Drake) for AVP_OpenInteng. AVP_OpenInteng's own code: see License.txt.
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const folder = path.join(root, 'avpx', 'shaders');
const out = path.join(root, 'src', 'host', 'shader_text_data.cpp');
const check = process.argv.includes('--check');

function fail(words) {
	console.error('make-shader-text: ' + words);
	process.exit(1);
}

if (!fs.existsSync(folder)) {
	fail('no ' + folder + ' (the avpx submodule is not checked out)');
}

// the shader files, in a fixed order (by name, byte order): only plain names of .vsh / .psh / .fxh, nothing else
const names = fs.readdirSync(folder).filter(n => /^[A-Za-z0-9_]+\.(vsh|psh|fxh)$/.test(n) && fs.statSync(path.join(folder, n)).isFile()).sort();

if (names.length === 0) {
	fail('no shader in ' + folder);
}

let text = '';
text += '// shader_text_data.cpp: GENERATED by tools/make-shader-text.js from avpx/shaders (' + names.length + ' files: the pinned AvPx\'s .vsh, .psh and the .fxh they include).\n';
text += '// NEVER EDIT BY HAND: "node tools/make-shader-text.js" makes it, "--check" says whether it is what avpx/shaders makes. Each text as its file holds it, a CRLF read as LF.\n';
text += '// The renderer takes them through R_SetShaderTextSource (shader_text.h). AVP_OpenInteng\'s own code: see License.txt, "AVP_OpenInteng\'s own code".\n\n';
text += '#include "shader_text.h"\n\nnamespace\n{\n';
names.forEach((name, i) => {
	const bytes = Buffer.from(fs.readFileSync(path.join(folder, name), 'latin1').replace(/\r\n/g, '\n'), 'latin1');
	text += '\t// ' + name + ', ' + bytes.length + ' bytes\n\tunsigned char const kText' + i + '[] =\n\t{\n';
	for (let at = 0; at < bytes.length; at += 32) {
		text += '\t\t' + Array.from(bytes.subarray(at, at + 32)).join(', ') + (at + 32 < bytes.length ? ',' : '') + '\n';
	}
	text += '\t};\n\n';
});
text += '}\n\nnamespace host\n{\n\tShaderTextEntry const kShaderTexts[] =\n\t{\n';
names.forEach((name, i) => {
	text += '\t\t{ "' + name + '", reinterpret_cast<char const *>(kText' + i + '), sizeof(kText' + i + ') },\n';
});
text += '\t};\n\n\tsize_t const kShaderTextCount = sizeof(kShaderTexts) / sizeof(kShaderTexts[0]);\n}\n';

if (check) {
	const now = fs.existsSync(out) ? fs.readFileSync(out, 'latin1').replace(/\r\n/g, '\n') : '';
	if (now !== text) {
		fail(path.relative(root, out) + ' is NOT what avpx/shaders makes (' + names.length + ' files): run node tools/make-shader-text.js');
	}
	console.log('make-shader-text: ' + path.relative(root, out) + ' is what avpx/shaders makes (' + names.length + ' files)');
} else {
	fs.writeFileSync(out, text, 'latin1');
	console.log('make-shader-text: wrote ' + path.relative(root, out) + ' (' + names.length + ' files, ' + text.length + ' bytes)');
}
